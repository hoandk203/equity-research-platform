// Generate the installer seed for market data from the accepted dataset:
//   node apps/etl/src/export-seed.ts
//   -> db/seed/market_seed.sql   (loads through pkg_market_import, same validation as etl:load)
//   -> db/seed/market_verify.sql (counts + reference values from lib/reference.ts)
// Both run as an administrator with CURRENT_SCHEMA = owner (db/install.sh, db/verify.sh).
import { join } from 'node:path';
import { ROOT } from './lib/config.ts';
import { loadDataset, planBatches } from './lib/dataset.ts';
import { writeText } from './lib/files.ts';
import { expectations } from './lib/reference.ts';

const q = (s: string | null | undefined) => (s === null || s === undefined ? 'NULL' : `'${s.replace(/'/g, "''")}'`);
const ts = (s: string | null) => (s ? `TO_TIMESTAMP_TZ(${q(s)}, 'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"')` : 'NULL');

/** Dates used for reference checks: valuation boundaries, a corrected session, year ends. */
export const VERIFY_DATES = ['2023-03-31', '2023-04-03', '2024-03-29', '2024-04-01', '2025-05-13', '2025-06-30', '2025-12-31'];

function main() {
  const ds = loadDataset();
  const plans = planBatches(ds);
  const version = ds.manifest.dataset_version;
  const lines: string[] = [
    `-- Generated by apps/etl/src/export-seed.ts from db/seed/market (${version}). Do not edit by hand.`,
    '-- Run as an administrator with CURRENT_SCHEMA = owner, after pilot_seed.sql (db/install.sh).',
    '-- Loads capital items, share counts and daily prices through pkg_market_import: the database',
    '-- re-validates every row (hashes, OHLC, calendar, corrections, year-end share check).',
    'WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK',
    'SET DEFINE OFF',
    'SET SERVEROUTPUT ON',
  ];
  const artVar = new Map<string, string>();
  const artifacts = [
    ...ds.manifest.artifacts.map((a) => ({ ...a })),
    ...ds.manifest.capital_provider_artifacts.map((c) => ({ source_code: 'CAFEF', source_name: 'CAFEF', kind: 'JSON', sha256: c.sha256, path: c.path,
      url: c.url, collected_at: null, note: null as string | null })),
  ];
  artifacts.forEach((a, i) => { artVar.set(a.sha256, `a${i}`); lines.push(`VARIABLE a${i} NUMBER`); });
  plans.forEach((p) => lines.push(`VARIABLE b_${p.suffix} NUMBER`));
  lines.push('BEGIN');
  for (const a of artifacts) {
    lines.push(`  pkg_financial_import.register_artifact(${q(a.source_code)}, ${q(a.source_name)}, ${q(a.kind)}, ${q(a.sha256)}, ${q(a.path)}, ${q(a.url)}, ${ts(a.collected_at)}, ${q(a.note)}, :${artVar.get(a.sha256)});`);
  }
  for (const p of plans) lines.push(`  pkg_market_import.create_batch(${q(`seed-${version}-${p.suffix}`)}, ${q(p.mapping)}, :b_${p.suffix});`);
  lines.push('END;', '/');
  for (const p of plans) {
    for (let i = 0; i < p.rows.length; i += 150) {
      lines.push('BEGIN');
      for (const r of p.rows.slice(i, i + 150)) {
        lines.push(`  pkg_market_import.stage_row(:b_${p.suffix}, ${r.rowNo}, ${q(r.kind)}, ${q(r.symbol)}, ${q(r.key)}, :${artVar.get(r.artifactSha)}, ${q(r.payload)});`);
      }
      lines.push('END;', '/');
    }
    lines.push(`EXEC pkg_market_import.seal_batch(:b_${p.suffix})`, 'COMMIT;', `EXEC pkg_market_import.process_batch(:b_${p.suffix})`);
    lines.push(`DECLARE s VARCHAR2(16); n NUMBER; BEGIN
  SELECT batch_status, imported_count INTO s, n FROM etl_batches WHERE batch_id = :b_${p.suffix};
  IF s <> 'COMPLETED' OR n <> ${p.rows.length} THEN raise_application_error(-20993, '${p.suffix} batch ' || s || ', imported ' || n || ' of ${p.rows.length}'); END IF;
END;
/`);
  }
  writeText(join(ROOT, 'db/seed/market_seed.sql'), lines.join('\n') + '\n');

  // Verification script: counts, reconciliation flags and independent reference values.
  const exp = expectations(ds.prices, ds.shares, ds.capital, VERIFY_DATES);
  const view = (m: string) => ['MARKET_CAP', 'EPS', 'PE', 'BVPS', 'PB'].includes(m) ? 'v_valuation_daily' : 'v_market_metrics_daily';
  const col = (m: string) => ({ CLOSE_PRICE: 'close_vnd', RETURN_1M: 'ret_1m', RETURN_1Y: 'ret_1y', MA20: 'ma20', MA200: 'ma200', VOLATILITY_1Y: 'volatility_1y',
    HIGH_52W: 'high_52w', LOW_52W: 'low_52w', MARKET_CAP: 'market_cap', EPS: 'eps', PE: 'pe', BVPS: 'bvps', PB: 'pb' } as Record<string, string>)[m];
  const corrRows = ds.corrections.length;
  const v: string[] = [
    `-- Generated with market_seed.sql (${version}). Fails unless the database reproduces the dataset and the`,
    '-- TypeScript reference values (apps/etl/src/lib/reference.ts) within 1e-9 relative.',
    'WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK',
    'SET DEFINE OFF',
    'SET SERVEROUTPUT ON',
    'DECLARE',
    '  n NUMBER; bad NUMBER := 0; checked NUMBER := 0;',
    '  PROCEDURE expect(p_label VARCHAR2, p_actual NUMBER, p_expected NUMBER) IS BEGIN',
    "    IF p_actual <> p_expected THEN raise_application_error(-20994, p_label || ': ' || p_actual || ' <> ' || p_expected); END IF;",
    "    DBMS_OUTPUT.PUT_LINE('OK ' || p_label || ' = ' || p_actual); END;",
    '  PROCEDURE near(p_label VARCHAR2, p_actual NUMBER, p_expected NUMBER) IS BEGIN',
    '    checked := checked + 1;',
    '    IF (p_actual IS NULL) <> (p_expected IS NULL) OR ABS(p_actual - p_expected) > 1e-9 * GREATEST(ABS(p_expected), 1) THEN',
    "      bad := bad + 1; DBMS_OUTPUT.PUT_LINE('MISMATCH ' || p_label || ' ' || NVL(TO_CHAR(p_actual), 'NULL') || ' expected ' || NVL(TO_CHAR(p_expected), 'NULL'));",
    '    END IF; END;',
    'BEGIN',
    `  SELECT COUNT(*) INTO n FROM v_price_history; expect('price rows (2 bases)', n, ${ds.prices.length * 2});`,
    `  SELECT COUNT(*) INTO n FROM v_market_metrics_daily; expect('sessions', n, ${ds.prices.length});`,
    `  SELECT COUNT(*) INTO n FROM v_price_corrections; expect('price corrections', n, ${corrRows});`,
    `  SELECT COUNT(*) INTO n FROM v_share_counts; expect('share counts', n, ${ds.shares.length});`,
    `  SELECT COUNT(*) INTO n FROM v_share_counts WHERE reconciliation_status = 'MATCHED_BS'; expect('year-end shares matched to balance sheet', n, ${ds.shares.filter((s) => s.bs_check === 'MATCHED_BS').length});`,
    `  SELECT COUNT(*) INTO n FROM v_capital_facts; expect('capital facts', n, ${ds.capital.length});`,
    `  SELECT COUNT(*) INTO n FROM v_capital_facts WHERE is_corrected = 1; expect('capital corrections', n, ${ds.capital.filter((c) => c.comparison === 'CORRECTED').length});`,
  ];
  for (const e of exp) {
    const value = e.value === null ? 'NULL' : String(e.value);
    v.push(`  SELECT MAX(${col(e.metric)}) INTO n FROM ${view(e.metric)} WHERE symbol = '${e.symbol}' AND trading_date = DATE '${e.date}'; near('${e.symbol} ${e.date} ${e.metric}', n, ${value});`);
  }
  v.push(
    "  IF bad > 0 THEN raise_application_error(-20995, bad || ' of ' || checked || ' reference values differ'); END IF;",
    "  DBMS_OUTPUT.PUT_LINE('OK ' || checked || ' market/valuation values match the TypeScript reference');",
    'END;', '/',
  );
  writeText(join(ROOT, 'db/seed/market_verify.sql'), v.join('\n') + '\n');
  console.log(`[etl:export-seed] market_seed.sql: ${plans.map((p) => `${p.suffix} ${p.rows.length}`).join(', ')}; market_verify.sql: ${exp.length} reference values`);
}

main();
