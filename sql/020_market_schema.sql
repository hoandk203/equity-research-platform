CREATE OR REPLACE TRIGGER trg_market_head_history
AFTER INSERT OR UPDATE OR DELETE ON market_heads
FOR EACH ROW
DECLARE v_action VARCHAR2(10);
BEGIN
  v_action := CASE WHEN INSERTING THEN 'INSERT' WHEN UPDATING THEN 'UPDATE' ELSE 'DELETE' END;
  INSERT INTO business_change_log(entity_name, entity_key, action_code, old_data, new_data, actor_name)
  VALUES ('MARKET_HEADS', TO_CHAR(COALESCE(:new.security_id, :old.security_id)) || ':' || COALESCE(:new.data_kind, :old.data_kind),
    v_action, TO_CHAR(:old.batch_id), TO_CHAR(:new.batch_id), SYS_CONTEXT('USERENV', 'SESSION_USER'));
END;
/
