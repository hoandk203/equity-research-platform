-- Market data and valuation inputs (contract erp-market/1.0.0, docs/18).
-- Run as SYSDBA with CURRENT_SCHEMA = owner, after 001-019. Never drops data:
-- daily_prices is recreated (partitioned) only when it is still empty and unpartitioned.
-- New tables: staging_market_rows, market_heads, share_counts, capital_facts,
-- price_corrections, valuation_policies, market_metric_definitions (23 -> 30 tables).
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF

-- Materialized views (022) need this privilege on the owner.
BEGIN
  EXECUTE IMMEDIATE 'GRANT CREATE MATERIALIZED VIEW TO ' || DBMS_ASSERT.SCHEMA_NAME(SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA'));
END;
/

DECLARE
  v_owner VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
  v_exists NUMBER; v_partitioned VARCHAR2(3); v_rows NUMBER;
BEGIN
  SELECT COUNT(*), MAX(partitioned) INTO v_exists, v_partitioned FROM all_tables
   WHERE owner = v_owner AND table_name = 'DAILY_PRICES';
  IF v_exists = 1 AND v_partitioned = 'NO' THEN
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM ' || DBMS_ASSERT.ENQUOTE_NAME(v_owner) || '.daily_prices' INTO v_rows;
    IF v_rows > 0 THEN
      raise_application_error(-20500, 'daily_prices already holds data; refusing to recreate it');
    END IF;
    EXECUTE IMMEDIATE 'DROP TABLE ' || DBMS_ASSERT.ENQUOTE_NAME(v_owner) || '.daily_prices PURGE';
  END IF;
END;
/

-- One staging row per source record; the payload JSON carries every typed field.
CREATE TABLE IF NOT EXISTS staging_market_rows (
  staging_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  batch_id NUMBER(19) NOT NULL,
  row_no NUMBER(19) NOT NULL,
  record_kind VARCHAR2(8 CHAR) NOT NULL,
  artifact_id NUMBER(19),
  source_symbol VARCHAR2(40 CHAR),
  record_key VARCHAR2(40 CHAR),
  row_status VARCHAR2(12 CHAR) DEFAULT 'PENDING' NOT NULL,
  payload CLOB NOT NULL,
  CONSTRAINT staging_market_rows_pk PRIMARY KEY (staging_id),
  CONSTRAINT staging_market_rows_u1 UNIQUE (batch_id, row_no),
  CONSTRAINT staging_market_rows_u2 UNIQUE (staging_id, batch_id),
  CONSTRAINT staging_market_rows_c1 CHECK (record_kind IN ('PRICE','SHARES','CAPITAL')),
  CONSTRAINT staging_market_rows_c2 CHECK (row_status IN ('PENDING','VALID','REJECTED','IMPORTED','SKIPPED')),
  CONSTRAINT staging_market_rows_c3 CHECK (payload IS JSON),
  CONSTRAINT staging_market_rows_f1 FOREIGN KEY (batch_id) REFERENCES etl_batches (batch_id),
  CONSTRAINT staging_market_rows_f2 FOREIGN KEY (artifact_id) REFERENCES source_artifacts (artifact_id)
);
COMMENT ON TABLE staging_market_rows IS 'Vùng nhận dữ liệu thị trường chưa tin cậy (giá, số cổ phiếu, chỉ tiêu vốn)';
COMMENT ON COLUMN staging_market_rows.record_kind IS 'PRICE/SHARES/CAPITAL';
COMMENT ON COLUMN staging_market_rows.record_key IS 'Ngày giao dịch, ngày hiệu lực hoặc năm-chỉ tiêu dạng thô';
COMMENT ON COLUMN staging_market_rows.payload IS 'Bản ghi JSON đầy đủ';
CREATE INDEX IF NOT EXISTS staging_market_rows_ix1 ON staging_market_rows (artifact_id);

