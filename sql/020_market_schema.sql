-- Daily prices: one row per security x session x basis x import batch. Yearly interval
-- partitions; small initial extents (partitions would otherwise start at 8 MB each).
CREATE TABLE IF NOT EXISTS daily_prices (
  price_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  security_id NUMBER(19) NOT NULL,
  trading_date DATE NOT NULL,
  batch_id NUMBER(19) NOT NULL,
  artifact_id NUMBER(19) NOT NULL,
  price_basis VARCHAR2(12 CHAR) NOT NULL,
  currency_code VARCHAR2(7 CHAR) NOT NULL,
  price_multiplier NUMBER(10) NOT NULL,
  open_price NUMBER(20,6),
  high_price NUMBER(20,6),
  low_price NUMBER(20,6),
  close_price NUMBER(20,6) NOT NULL,
  volume NUMBER(24,0),
  is_corrected NUMBER(1) DEFAULT 0 NOT NULL,
  CONSTRAINT daily_prices_pk PRIMARY KEY (price_id),
  CONSTRAINT daily_prices_c1 CHECK (price_basis IN ('ADJUSTED','UNADJUSTED')),
  CONSTRAINT daily_prices_c2 CHECK (trading_date = TRUNC(trading_date)),
  CONSTRAINT daily_prices_c3 CHECK (close_price > 0),
  CONSTRAINT daily_prices_c4 CHECK (open_price IS NULL OR open_price > 0),
  CONSTRAINT daily_prices_c5 CHECK (low_price IS NULL OR low_price > 0),
  CONSTRAINT daily_prices_c6 CHECK (high_price IS NULL OR high_price > 0),
  CONSTRAINT daily_prices_c7 CHECK (volume IS NULL OR volume >= 0),
  CONSTRAINT daily_prices_c8 CHECK (high_price IS NULL OR low_price IS NULL OR high_price >= low_price),
  CONSTRAINT daily_prices_c9 CHECK (high_price IS NULL OR high_price >= close_price),
  CONSTRAINT daily_prices_c10 CHECK (low_price IS NULL OR low_price <= close_price),
  CONSTRAINT daily_prices_c11 CHECK (high_price IS NULL OR open_price IS NULL OR high_price >= open_price),
  CONSTRAINT daily_prices_c12 CHECK (low_price IS NULL OR open_price IS NULL OR low_price <= open_price),
  CONSTRAINT daily_prices_c13 CHECK (price_multiplier IN (1,1000)),
  CONSTRAINT daily_prices_c14 CHECK (currency_code = 'VND'),
  CONSTRAINT daily_prices_c15 CHECK (is_corrected IN (0,1)),
  CONSTRAINT daily_prices_f1 FOREIGN KEY (security_id) REFERENCES securities (security_id),
  CONSTRAINT daily_prices_f2 FOREIGN KEY (artifact_id) REFERENCES source_artifacts (artifact_id),
  CONSTRAINT daily_prices_f3 FOREIGN KEY (batch_id) REFERENCES etl_batches (batch_id)
)
SEGMENT CREATION DEFERRED STORAGE (INITIAL 64K NEXT 64K)
PARTITION BY RANGE (trading_date) INTERVAL (NUMTOYMINTERVAL(1, 'YEAR'))
(PARTITION p_before_2022 VALUES LESS THAN (DATE '2022-01-01'));
COMMENT ON TABLE daily_prices IS 'Giá ngày theo đợt nhập; mỗi phiên hai dòng (giá gốc, giá điều chỉnh); phân vùng theo năm';
COMMENT ON COLUMN daily_prices.price_id IS 'Surrogate ID, identity GENERATED BY DEFAULT ON NULL';
COMMENT ON COLUMN daily_prices.security_id IS 'Chứng khoán';
COMMENT ON COLUMN daily_prices.trading_date IS 'Ngày giao dịch không có phần giờ (khóa phân vùng)';
COMMENT ON COLUMN daily_prices.batch_id IS 'Đợt nhập; chuỗi hiện hành do market_heads chỉ định';
COMMENT ON COLUMN daily_prices.artifact_id IS 'Tệp nguồn (hash)';
COMMENT ON COLUMN daily_prices.price_basis IS 'UNADJUSTED (giá khớp lệnh) / ADJUSTED (điều chỉnh sự kiện doanh nghiệp tại ngày tải)';
COMMENT ON COLUMN daily_prices.currency_code IS 'VND';
COMMENT ON COLUMN daily_prices.price_multiplier IS 'Hệ số sang đồng (nguồn tính bằng nghìn đồng = 1000)';
COMMENT ON COLUMN daily_prices.open_price IS 'Giá mở cửa (đơn vị nguồn)';
COMMENT ON COLUMN daily_prices.high_price IS 'Giá cao nhất';
COMMENT ON COLUMN daily_prices.low_price IS 'Giá thấp nhất';
COMMENT ON COLUMN daily_prices.close_price IS 'Giá đóng cửa';
COMMENT ON COLUMN daily_prices.volume IS 'Khối lượng khớp lệnh (cổ phiếu)';
COMMENT ON COLUMN daily_prices.is_corrected IS '1 khi có dòng price_corrections (đã thay giá trị nhà cung cấp)';
CREATE UNIQUE INDEX IF NOT EXISTS daily_prices_u1 ON daily_prices (security_id, price_basis, batch_id, trading_date) LOCAL;
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE daily_prices ADD CONSTRAINT daily_prices_u1 '
    || 'UNIQUE (security_id, price_basis, batch_id, trading_date) USING INDEX daily_prices_u1';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-2261, -2264) THEN RAISE; END IF;
END;
/
CREATE INDEX IF NOT EXISTS daily_prices_ix2 ON daily_prices (artifact_id) LOCAL;
CREATE INDEX IF NOT EXISTS daily_prices_ix3 ON daily_prices (batch_id) LOCAL;

