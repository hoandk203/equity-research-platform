CREATE OR REPLACE TRIGGER trg_market_head_guard
BEFORE INSERT OR UPDATE ON market_heads
FOR EACH ROW
DECLARE v_status VARCHAR2(16); v_contract VARCHAR2(40);
BEGIN
  SELECT batch_status, contract_version INTO v_status, v_contract FROM etl_batches WHERE batch_id = :new.batch_id;
  IF v_contract <> 'erp-market/1.0.0' OR v_status NOT IN ('IMPORTING','COMPLETED','PARTIAL') THEN
    raise_application_error(-20535, 'Market head must reference an imported erp-market batch');
  END IF;
  IF UPDATING AND :new.lock_version <> :old.lock_version + 1 THEN
    raise_application_error(-20536, 'Market head update must increment lock_version by one');
  END IF;
END;
